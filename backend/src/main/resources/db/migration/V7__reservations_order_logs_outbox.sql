CREATE TABLE inventory_reservation (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 order_id BIGINT UNSIGNED NOT NULL,
 order_item_id BIGINT UNSIGNED NOT NULL UNIQUE,
 sku_id BIGINT UNSIGNED NOT NULL,
 quantity INT UNSIGNED NOT NULL,
 status VARCHAR(16) COLLATE utf8mb4_bin NOT NULL DEFAULT 'RESERVED',
 expires_at DATETIME(3) NOT NULL,
 FOREIGN KEY(order_id) REFERENCES trade_order(id) ON DELETE RESTRICT,
 FOREIGN KEY(order_item_id) REFERENCES order_item(id) ON DELETE RESTRICT,
 FOREIGN KEY(sku_id) REFERENCES sku(id) ON DELETE RESTRICT,
 CHECK(quantity>0), CHECK(status IN ('RESERVED','COMMITTED','RELEASED')),
 INDEX ix_reservation_order_status(order_id,status),
 INDEX ix_reservation_status_expires(status,expires_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE order_status_log (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 order_id BIGINT UNSIGNED NOT NULL,
 from_status VARCHAR(24) COLLATE utf8mb4_bin NULL,
 to_status VARCHAR(24) COLLATE utf8mb4_bin NOT NULL,
 action VARCHAR(50) COLLATE utf8mb4_bin NOT NULL,
 operator_id BIGINT UNSIGNED NULL,
 reason VARCHAR(300) NOT NULL,
 trace_id VARCHAR(64) COLLATE utf8mb4_bin NOT NULL,
 FOREIGN KEY(order_id) REFERENCES trade_order(id) ON DELETE RESTRICT,
 FOREIGN KEY(operator_id) REFERENCES iam_user(id) ON DELETE RESTRICT,
 CHECK(from_status IS NULL OR from_status IN ('PENDING_PAYMENT','CLOSING','PAID','SHIPPED','COMPLETED','CANCELLED','CLOSED_REFUND')),
 CHECK(to_status IN ('PENDING_PAYMENT','CLOSING','PAID','SHIPPED','COMPLETED','CANCELLED','CLOSED_REFUND')),
 INDEX ix_order_log_created(order_id,created_at,id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TRIGGER order_status_log_reject_update BEFORE UPDATE ON order_status_log FOR EACH ROW SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='order_status_log is append-only';
CREATE TRIGGER order_status_log_reject_delete BEFORE DELETE ON order_status_log FOR EACH ROW SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='order_status_log is append-only';

CREATE TABLE outbox_event (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 event_id VARCHAR(64) COLLATE utf8mb4_bin NOT NULL UNIQUE,
 event_type VARCHAR(80) COLLATE utf8mb4_bin NOT NULL,
 schema_version INT UNSIGNED NOT NULL DEFAULT 1,
 aggregate_type VARCHAR(40) COLLATE utf8mb4_bin NOT NULL,
 aggregate_id VARCHAR(64) COLLATE utf8mb4_bin NOT NULL,
 payload JSON NOT NULL,
 trace_id VARCHAR(64) COLLATE utf8mb4_bin NOT NULL,
 status VARCHAR(16) COLLATE utf8mb4_bin NOT NULL DEFAULT 'PENDING',
 attempts INT UNSIGNED NOT NULL DEFAULT 0,
 next_attempt_at DATETIME(3) NOT NULL,
 published_at DATETIME(3) NULL,
 lease_owner VARCHAR(80) COLLATE utf8mb4_bin NULL,
 lease_until DATETIME(3) NULL,
 CHECK(status IN ('PENDING','PUBLISHED','FAILED')),
 INDEX ix_outbox_due(status,next_attempt_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE job_lease (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 job_name VARCHAR(80) COLLATE utf8mb4_bin NOT NULL UNIQUE,
 owner VARCHAR(80) COLLATE utf8mb4_bin NOT NULL,
 lease_until DATETIME(3) NOT NULL,
 version INT UNSIGNED NOT NULL DEFAULT 1
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
