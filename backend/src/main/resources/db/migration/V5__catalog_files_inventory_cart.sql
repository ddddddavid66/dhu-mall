-- 新增阶段 C 结构；无账号、口令或业务种子。
CREATE TABLE file_object (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  owner_user_id BIGINT UNSIGNED NOT NULL,
  shop_id BIGINT UNSIGNED NULL,
  purpose VARCHAR(24) COLLATE utf8mb4_bin NOT NULL,
  visibility VARCHAR(16) COLLATE utf8mb4_bin NOT NULL,
  storage_key VARCHAR(255) COLLATE utf8mb4_bin NOT NULL UNIQUE,
  mime_type VARCHAR(40) NOT NULL,
  byte_size BIGINT UNSIGNED NOT NULL,
  sha256 VARCHAR(64) COLLATE utf8mb4_bin NOT NULL,
  status VARCHAR(16) COLLATE utf8mb4_bin NOT NULL DEFAULT 'ACTIVE',
  FOREIGN KEY (owner_user_id) REFERENCES iam_user(id) ON DELETE RESTRICT,
  FOREIGN KEY (shop_id) REFERENCES shop(id) ON DELETE RESTRICT,
  CHECK(purpose IN ('BOOK_COVER','AFTER_SALE_EVIDENCE')),
  CHECK((purpose='BOOK_COVER' AND visibility='PUBLIC') OR (purpose='AFTER_SALE_EVIDENCE' AND visibility='PRIVATE')),
  CHECK(status IN ('ACTIVE','DELETED')),
  INDEX ix_file_owner_created(owner_user_id,created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE category (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  parent_id BIGINT UNSIGNED NULL,
  name VARCHAR(50) NOT NULL,
  sort_order INT NOT NULL DEFAULT 0,
  status VARCHAR(16) COLLATE utf8mb4_bin NOT NULL DEFAULT 'ACTIVE',
  FOREIGN KEY (parent_id) REFERENCES category(id) ON DELETE RESTRICT,
  CHECK(status IN ('ACTIVE','DISABLED')),
  INDEX ix_category_parent_sort(parent_id,sort_order)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE book (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  isbn VARCHAR(13) COLLATE utf8mb4_bin NOT NULL UNIQUE,
  title VARCHAR(200) NOT NULL,
  author VARCHAR(200) NOT NULL,
  publisher VARCHAR(120) NOT NULL,
  publication_date DATE NULL,
  category_id BIGINT UNSIGNED NOT NULL,
  description VARCHAR(5000) NOT NULL,
  cover_file_id BIGINT UNSIGNED NULL,
  status VARCHAR(16) COLLATE utf8mb4_bin NOT NULL DEFAULT 'ACTIVE',
  FOREIGN KEY (category_id) REFERENCES category(id) ON DELETE RESTRICT,
  FOREIGN KEY (cover_file_id) REFERENCES file_object(id) ON DELETE RESTRICT,
  CHECK(status IN ('ACTIVE','DISABLED')),
  INDEX ix_book_category_status_id(category_id,status,id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE product (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  shop_id BIGINT UNSIGNED NOT NULL,
  book_id BIGINT UNSIGNED NOT NULL,
  description VARCHAR(5000) NOT NULL,
  status VARCHAR(16) COLLATE utf8mb4_bin NOT NULL DEFAULT 'DRAFT',
  featured TINYINT NOT NULL DEFAULT 0,
  version INT UNSIGNED NOT NULL DEFAULT 1,
  FOREIGN KEY (shop_id) REFERENCES shop(id) ON DELETE RESTRICT,
  FOREIGN KEY (book_id) REFERENCES book(id) ON DELETE RESTRICT,
  UNIQUE(shop_id,book_id),
  CHECK(status IN ('DRAFT','ON_SALE','OFF_SHELF')),
  CHECK(featured IN (0,1)),
  INDEX ix_product_shop_status(shop_id,status),
  INDEX ix_product_status_featured(status,featured)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE sku (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  product_id BIGINT UNSIGNED NOT NULL UNIQUE,
  sku_code VARCHAR(64) COLLATE utf8mb4_bin NOT NULL UNIQUE,
  sale_price DECIMAL(12,2) NOT NULL,
  version INT UNSIGNED NOT NULL DEFAULT 1,
  FOREIGN KEY (product_id) REFERENCES product(id) ON DELETE RESTRICT,
  CHECK(sale_price>0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE inventory (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  sku_id BIGINT UNSIGNED NOT NULL UNIQUE,
  on_hand INT UNSIGNED NOT NULL DEFAULT 0,
  reserved INT UNSIGNED NOT NULL DEFAULT 0,
  version INT UNSIGNED NOT NULL DEFAULT 1,
  FOREIGN KEY (sku_id) REFERENCES sku(id) ON DELETE RESTRICT,
  CHECK(reserved<=on_hand)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE cart_item (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  user_id BIGINT UNSIGNED NOT NULL,
  sku_id BIGINT UNSIGNED NOT NULL,
  quantity INT UNSIGNED NOT NULL,
  selected TINYINT NOT NULL DEFAULT 1,
  FOREIGN KEY (user_id) REFERENCES iam_user(id) ON DELETE RESTRICT,
  FOREIGN KEY (sku_id) REFERENCES sku(id) ON DELETE RESTRICT,
  UNIQUE(user_id,sku_id),
  CHECK(quantity BETWEEN 1 AND 99),
  CHECK(selected IN (0,1))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE idempotency_record (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  user_id BIGINT UNSIGNED NOT NULL,
  operation_id VARCHAR(40) COLLATE utf8mb4_bin NOT NULL,
  idempotency_key VARCHAR(64) COLLATE utf8mb4_bin NOT NULL,
  request_hash VARCHAR(64) COLLATE utf8mb4_bin NOT NULL,
  status VARCHAR(16) COLLATE utf8mb4_bin NOT NULL DEFAULT 'PROCESSING',
  resource_type VARCHAR(40) COLLATE utf8mb4_bin NULL,
  resource_id VARCHAR(64) COLLATE utf8mb4_bin NULL,
  response_snapshot JSON NULL,
  replay_until DATETIME(3) NOT NULL,
  retain_until DATETIME(3) NOT NULL,
  FOREIGN KEY (user_id) REFERENCES iam_user(id) ON DELETE RESTRICT,
  UNIQUE(user_id,operation_id,idempotency_key),
  CHECK(status IN ('PROCESSING','SUCCEEDED')),
  INDEX ix_idempotency_retention(retain_until)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

