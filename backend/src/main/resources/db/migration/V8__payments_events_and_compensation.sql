CREATE TABLE payment (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3), updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 payment_no VARCHAR(40) COLLATE utf8mb4_bin NOT NULL UNIQUE, order_id BIGINT UNSIGNED NOT NULL UNIQUE,
 provider VARCHAR(24) COLLATE utf8mb4_bin NOT NULL, status VARCHAR(16) COLLATE utf8mb4_bin NOT NULL DEFAULT 'INIT',
 amount DECIMAL(12,2) NOT NULL, currency VARCHAR(3) COLLATE utf8mb4_bin NOT NULL DEFAULT 'CNY',
 channel_trade_no VARCHAR(80) COLLATE utf8mb4_bin NULL, paid_at DATETIME(3) NULL, last_checked_at DATETIME(3) NULL, failure_code VARCHAR(80) NULL,
 FOREIGN KEY(order_id) REFERENCES trade_order(id) ON DELETE RESTRICT,
 UNIQUE(provider,channel_trade_no), CHECK(provider IN ('ALIPAY_SANDBOX','LOCAL_MOCK')),
 CHECK(status IN ('INIT','PENDING','SUCCEEDED','CLOSED')), CHECK(amount>0), CHECK(currency='CNY'), INDEX ix_payment_status_updated(status,updated_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE payment_event (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3), updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 payment_id BIGINT UNSIGNED NULL, provider VARCHAR(24) COLLATE utf8mb4_bin NOT NULL,
 event_key VARCHAR(128) COLLATE utf8mb4_bin NOT NULL, channel_trade_no VARCHAR(80) COLLATE utf8mb4_bin NULL,
 event_type VARCHAR(40) NOT NULL, verified TINYINT UNSIGNED NOT NULL, payload_digest VARCHAR(64) COLLATE utf8mb4_bin NOT NULL,
 processed_at DATETIME(3) NULL, processing_status VARCHAR(16) COLLATE utf8mb4_bin NOT NULL DEFAULT 'RECEIVED', trace_id VARCHAR(64) NOT NULL,
 FOREIGN KEY(payment_id) REFERENCES payment(id) ON DELETE RESTRICT, UNIQUE(provider,event_key),
 CHECK(provider IN ('ALIPAY_SANDBOX','LOCAL_MOCK')), CHECK(verified IN (0,1)), CHECK(processing_status IN ('RECEIVED','PROCESSED','REJECTED'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE refund (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3), updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 refund_no VARCHAR(40) COLLATE utf8mb4_bin NOT NULL UNIQUE, payment_id BIGINT UNSIGNED NOT NULL,
 after_sale_id BIGINT UNSIGNED NULL UNIQUE, reason_type VARCHAR(24) COLLATE utf8mb4_bin NOT NULL,
 status VARCHAR(16) COLLATE utf8mb4_bin NOT NULL DEFAULT 'CREATED', amount DECIMAL(12,2) NOT NULL,
 channel_refund_no VARCHAR(80) NULL, requested_by BIGINT UNSIGNED NULL, succeeded_at DATETIME(3) NULL, failure_code VARCHAR(80) NULL,
 FOREIGN KEY(payment_id) REFERENCES payment(id) ON DELETE RESTRICT, FOREIGN KEY(after_sale_id) REFERENCES after_sale(id) ON DELETE RESTRICT,
 FOREIGN KEY(requested_by) REFERENCES iam_user(id) ON DELETE RESTRICT,
 CHECK(reason_type IN ('NORMAL_AFTER_SALE','LATE_PAYMENT_COMPENSATION')),
 CHECK((reason_type='NORMAL_AFTER_SALE' AND after_sale_id IS NOT NULL) OR (reason_type='LATE_PAYMENT_COMPENSATION' AND after_sale_id IS NULL)),
 CHECK(status IN ('CREATED','PROCESSING','SUCCEEDED','FAILED')), CHECK(amount>0),
 UNIQUE(payment_id,(CASE WHEN reason_type='LATE_PAYMENT_COMPENSATION' THEN reason_type ELSE NULL END)),
 INDEX ix_refund_status_updated(status,updated_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE reconciliation_run (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3), updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 provider VARCHAR(24) COLLATE utf8mb4_bin NOT NULL, bill_date DATE NOT NULL, status VARCHAR(16) NOT NULL DEFAULT 'PENDING',
 checked_count INT UNSIGNED NOT NULL DEFAULT 0, difference_count INT UNSIGNED NOT NULL DEFAULT 0, completed_at DATETIME(3) NULL, evidence_file_key VARCHAR(255) NULL,
 UNIQUE(provider,bill_date), CHECK(provider IN ('ALIPAY_SANDBOX','LOCAL_MOCK')), CHECK(status IN ('PENDING','RUNNING','SUCCEEDED','FAILED'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE reconciliation_issue (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3), updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 run_id BIGINT UNSIGNED NULL, order_id BIGINT UNSIGNED NULL, payment_id BIGINT UNSIGNED NULL, refund_id BIGINT UNSIGNED NULL,
 issue_key VARCHAR(128) COLLATE utf8mb4_bin NOT NULL UNIQUE, issue_type VARCHAR(40) NOT NULL,
 expected_amount DECIMAL(12,2) NULL, actual_amount DECIMAL(12,2) NULL, status VARCHAR(16) NOT NULL DEFAULT 'OPEN',
 resolution VARCHAR(1000) NULL, resolved_by BIGINT UNSIGNED NULL, resolved_at DATETIME(3) NULL,
 FOREIGN KEY(run_id) REFERENCES reconciliation_run(id) ON DELETE RESTRICT, FOREIGN KEY(order_id) REFERENCES trade_order(id) ON DELETE RESTRICT,
 FOREIGN KEY(payment_id) REFERENCES payment(id) ON DELETE RESTRICT, FOREIGN KEY(refund_id) REFERENCES refund(id) ON DELETE RESTRICT,
 FOREIGN KEY(resolved_by) REFERENCES iam_user(id) ON DELETE RESTRICT, CHECK(status IN ('OPEN','RESOLVED')), INDEX ix_issue_status_created(status,created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
