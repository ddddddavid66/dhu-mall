-- 为库存流水和凭证鉴权建立真实外键依赖的空结构，不开放交易/售后/评价写接口，不造业务样本。
CREATE TABLE checkout_preview (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  user_id BIGINT UNSIGNED NOT NULL,
  address_id BIGINT UNSIGNED NOT NULL,
  items_snapshot JSON NOT NULL,
  address_version_hash VARCHAR(64) COLLATE utf8mb4_bin NOT NULL,
  amount DECIMAL(12,2) NOT NULL,
  expires_at DATETIME(3) NOT NULL,
  used_at DATETIME(3) NULL,
  FOREIGN KEY (user_id) REFERENCES iam_user(id) ON DELETE RESTRICT,
  FOREIGN KEY (address_id) REFERENCES user_address(id) ON DELETE RESTRICT,
  CHECK(amount>=0),
  INDEX ix_preview_user_expires(user_id,expires_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE checkout_batch (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  batch_no VARCHAR(40) COLLATE utf8mb4_bin NOT NULL UNIQUE,
  user_id BIGINT UNSIGNED NOT NULL,
  preview_id BIGINT UNSIGNED NOT NULL UNIQUE,
  total_amount DECIMAL(12,2) NOT NULL,
  FOREIGN KEY (user_id) REFERENCES iam_user(id) ON DELETE RESTRICT,
  FOREIGN KEY (preview_id) REFERENCES checkout_preview(id) ON DELETE RESTRICT,
  CHECK(total_amount>=0),
  INDEX ix_batch_user_created(user_id,created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE trade_order (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  order_no VARCHAR(40) COLLATE utf8mb4_bin NOT NULL UNIQUE,
  batch_id BIGINT UNSIGNED NOT NULL,
  user_id BIGINT UNSIGNED NOT NULL,
  shop_id BIGINT UNSIGNED NOT NULL,
  status VARCHAR(24) COLLATE utf8mb4_bin NOT NULL DEFAULT 'PENDING_PAYMENT',
  financial_status VARCHAR(24) COLLATE utf8mb4_bin NOT NULL DEFAULT 'UNPAID',
  goods_amount DECIMAL(12,2) NOT NULL,
  freight_amount DECIMAL(12,2) NOT NULL DEFAULT 0.00,
  payable_amount DECIMAL(12,2) NOT NULL,
  refunded_amount DECIMAL(12,2) NOT NULL DEFAULT 0.00,
  receiver_name VARCHAR(40) NOT NULL,
  receiver_phone VARCHAR(32) NOT NULL,
  receiver_address VARCHAR(300) NOT NULL,
  expires_at DATETIME(3) NOT NULL,
  paid_at DATETIME(3) NULL,
  shipped_at DATETIME(3) NULL,
  completed_at DATETIME(3) NULL,
  closed_at DATETIME(3) NULL,
  close_reason VARCHAR(300) NULL,
  version INT UNSIGNED NOT NULL DEFAULT 1,
  FOREIGN KEY (batch_id) REFERENCES checkout_batch(id) ON DELETE RESTRICT,
  FOREIGN KEY (user_id) REFERENCES iam_user(id) ON DELETE RESTRICT,
  FOREIGN KEY (shop_id) REFERENCES shop(id) ON DELETE RESTRICT,
  UNIQUE(batch_id,shop_id),
  CHECK(status IN ('PENDING_PAYMENT','PAID','CLOSING','CANCELLED','SHIPPED','COMPLETED','CLOSED_REFUND')),
  CHECK(financial_status IN ('UNPAID','PAID','PARTIALLY_REFUNDED','REFUNDED')),
  CHECK(goods_amount>=0 AND freight_amount>=0 AND payable_amount=goods_amount+freight_amount AND refunded_amount BETWEEN 0 AND payable_amount),
  INDEX ix_order_user_created(user_id,created_at,id),
  INDEX ix_order_shop_status_created(shop_id,status,created_at),
  INDEX ix_order_status_expires(status,expires_at),
  INDEX ix_order_completed(completed_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE order_item (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  order_id BIGINT UNSIGNED NOT NULL,
  sku_id BIGINT UNSIGNED NOT NULL,
  book_id BIGINT UNSIGNED NOT NULL,
  product_id BIGINT UNSIGNED NOT NULL,
  book_title VARCHAR(200) NOT NULL,
  isbn VARCHAR(13) COLLATE utf8mb4_bin NOT NULL,
  cover_storage_key VARCHAR(255) COLLATE utf8mb4_bin NULL,
  sku_code VARCHAR(64) COLLATE utf8mb4_bin NOT NULL,
  unit_price DECIMAL(12,2) NOT NULL,
  quantity INT UNSIGNED NOT NULL,
  line_amount DECIMAL(12,2) NOT NULL,
  refunded_quantity INT UNSIGNED NOT NULL DEFAULT 0,
  refunded_amount DECIMAL(12,2) NOT NULL DEFAULT 0.00,
  FOREIGN KEY (order_id) REFERENCES trade_order(id) ON DELETE RESTRICT,
  FOREIGN KEY (sku_id) REFERENCES sku(id) ON DELETE RESTRICT,
  FOREIGN KEY (book_id) REFERENCES book(id) ON DELETE RESTRICT,
  FOREIGN KEY (product_id) REFERENCES product(id) ON DELETE RESTRICT,
  UNIQUE(order_id,sku_id),
  CHECK(quantity BETWEEN 1 AND 99 AND unit_price>0 AND line_amount=unit_price*quantity AND refunded_quantity<=quantity AND refunded_amount BETWEEN 0 AND line_amount)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE after_sale (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  after_sale_no VARCHAR(40) COLLATE utf8mb4_bin NOT NULL UNIQUE,
  order_id BIGINT UNSIGNED NOT NULL,
  order_item_id BIGINT UNSIGNED NOT NULL,
  user_id BIGINT UNSIGNED NOT NULL,
  type VARCHAR(24) COLLATE utf8mb4_bin NOT NULL,
  quantity INT UNSIGNED NOT NULL,
  requested_amount DECIMAL(12,2) NOT NULL,
  reason VARCHAR(500) NOT NULL,
  status VARCHAR(24) COLLATE utf8mb4_bin NOT NULL DEFAULT 'REQUESTED',
  reviewed_by BIGINT UNSIGNED NULL,
  reviewed_at DATETIME(3) NULL,
  review_note VARCHAR(500) NULL,
  return_deadline DATETIME(3) NULL,
  return_carrier VARCHAR(50) NULL,
  return_tracking_no VARCHAR(80) COLLATE utf8mb4_bin NULL,
  received_by BIGINT UNSIGNED NULL,
  received_at DATETIME(3) NULL,
  restock_quantity INT UNSIGNED NOT NULL DEFAULT 0,
  inspection_note VARCHAR(500) NULL,
  active_order_item_id BIGINT UNSIGNED GENERATED ALWAYS AS (CASE WHEN status IN ('REQUESTED','APPROVED','RETURNING','RECEIVED','REFUNDING') THEN order_item_id ELSE NULL END) STORED UNIQUE,
  FOREIGN KEY (order_id) REFERENCES trade_order(id) ON DELETE RESTRICT,
  FOREIGN KEY (order_item_id) REFERENCES order_item(id) ON DELETE RESTRICT,
  FOREIGN KEY (user_id) REFERENCES iam_user(id) ON DELETE RESTRICT,
  FOREIGN KEY (reviewed_by) REFERENCES iam_user(id) ON DELETE RESTRICT,
  FOREIGN KEY (received_by) REFERENCES iam_user(id) ON DELETE RESTRICT,
  CHECK(type IN ('REFUND_ONLY','RETURN_REFUND')),
  CHECK(status IN ('REQUESTED','APPROVED','RETURNING','RECEIVED','REFUNDING','REJECTED','CANCELLED','COMPLETED','EXPIRED')),
  CHECK(quantity BETWEEN 1 AND 99 AND requested_amount>0 AND restock_quantity IN (0,quantity)),
  INDEX ix_after_sale_item_status(order_item_id,status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE after_sale_evidence (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  after_sale_id BIGINT UNSIGNED NOT NULL,
  file_id BIGINT UNSIGNED NOT NULL,
  FOREIGN KEY (after_sale_id) REFERENCES after_sale(id) ON DELETE RESTRICT,
  FOREIGN KEY (file_id) REFERENCES file_object(id) ON DELETE RESTRICT,
  UNIQUE(after_sale_id,file_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE review (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  order_item_id BIGINT UNSIGNED NOT NULL UNIQUE,
  user_id BIGINT UNSIGNED NOT NULL,
  product_id BIGINT UNSIGNED NOT NULL,
  rating TINYINT UNSIGNED NOT NULL,
  content VARCHAR(1000) NOT NULL,
  status VARCHAR(16) COLLATE utf8mb4_bin NOT NULL DEFAULT 'VISIBLE',
  moderated_by BIGINT UNSIGNED NULL,
  moderation_reason VARCHAR(300) NULL,
  FOREIGN KEY (order_item_id) REFERENCES order_item(id) ON DELETE RESTRICT,
  FOREIGN KEY (user_id) REFERENCES iam_user(id) ON DELETE RESTRICT,
  FOREIGN KEY (product_id) REFERENCES product(id) ON DELETE RESTRICT,
  FOREIGN KEY (moderated_by) REFERENCES iam_user(id) ON DELETE RESTRICT,
  CHECK(rating BETWEEN 1 AND 5),
  CHECK(status IN ('VISIBLE','HIDDEN')),
  INDEX ix_review_product_status_created(product_id,status,created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE inventory_movement (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  sku_id BIGINT UNSIGNED NOT NULL,
  order_item_id BIGINT UNSIGNED NULL,
  after_sale_id BIGINT UNSIGNED NULL,
  movement_type VARCHAR(32) COLLATE utf8mb4_bin NOT NULL,
  business_key VARCHAR(100) COLLATE utf8mb4_bin NOT NULL UNIQUE,
  on_hand_delta INT NOT NULL,
  reserved_delta INT NOT NULL,
  on_hand_after INT UNSIGNED NOT NULL,
  reserved_after INT UNSIGNED NOT NULL,
  reason VARCHAR(300) NOT NULL,
  operator_id BIGINT UNSIGNED NULL,
  trace_id VARCHAR(64) COLLATE utf8mb4_bin NOT NULL,
  FOREIGN KEY (sku_id) REFERENCES sku(id) ON DELETE RESTRICT,
  FOREIGN KEY (order_item_id) REFERENCES order_item(id) ON DELETE RESTRICT,
  FOREIGN KEY (after_sale_id) REFERENCES after_sale(id) ON DELETE RESTRICT,
  FOREIGN KEY (operator_id) REFERENCES iam_user(id) ON DELETE RESTRICT,
  CHECK(movement_type IN ('MANUAL_ADJUST','RESERVE','COMMIT','RELEASE','REFUND_RESTOCK','RETURN_RESTOCK')),
  CHECK(reserved_after<=on_hand_after),
  INDEX ix_movement_sku_created(sku_id,created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TRIGGER inventory_movement_reject_update BEFORE UPDATE ON inventory_movement FOR EACH ROW SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='inventory_movement is append-only';
CREATE TRIGGER inventory_movement_reject_delete BEFORE DELETE ON inventory_movement FOR EACH ROW SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='inventory_movement is append-only';
